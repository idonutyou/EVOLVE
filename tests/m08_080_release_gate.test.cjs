'use strict';
// M08 80% release gate: SHOP preview entitlement and mission reward isolation.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const engine=require('../web/shop-experience-v621.js');
const rewards=require('../web/m08-mission-rewards-v624.js');
const makeStorage=()=>{
 const m=new Map([['EVOLVE_V575_BATTLE_SAVE','SAVE_PRESERVED'],['EVOLVE_M03_ENTITLEMENT_SAVE','ENTITLEMENT_PRESERVED']]);
 return {getItem:k=>m.has(k)?m.get(k):null,setItem:(k,v)=>m.set(k,v),read:k=>m.get(k),map:m};
};
const storage=makeStorage(),clock=()=>Date.parse('2026-10-01T05:30:00Z');
const day=engine.kstDay(clock());
const store=engine.createStore({storage,clock}),ui=rewards.createController({store});
assert.equal(ui.balance(),0);
assert.deepEqual(Object.values(ui.status()).map(x=>x.ready),[false,false,false]);
assert.throws(()=>ui.claim('stage'),/MISSION_NOT_COMPLETE/);
storage.setItem('EVOLVE_M08_STAGE_MISSION_V622_V1',JSON.stringify({schema:'evolve.m08.stage.v622.1',days:{[day]:true}}));
storage.setItem('EVOLVE_M08_RUNTIME_MISSIONS_V623_V1',JSON.stringify({schema:'evolve.m08.runtime.v623.1',days:{[day]:{runEnds:1,discoveries:1}}}));
for(const k of ['stage','run','codex'])assert.equal(ui.status()[k].ready,true);
for(const k of ['stage','run','codex'])ui.claim(k);
assert.equal(ui.balance(),25);
assert.throws(()=>ui.claim('run'),/ALREADY_CLAIMED/);
assert.equal(ui.balance(),25);
assert.equal(store.snapshot().firstPurchase,false,'daily missions do not consume first purchase');
const first=store.order('crystal100','m08_080_first_order_request_001');
assert.equal(first.receipt.charged,false);
assert.equal(first.receipt.firstBonus,50);
assert.equal(ui.balance(),175);
const cosmetic=store.order('crimson','m08_080_crimson_request_001');
assert.equal(cosmetic.receipt.charged,false);
assert.equal(cosmetic.receipt.spentCrystals,120);
assert.equal(store.snapshot().owned.crimson,true);
assert.equal(ui.balance(),55);
const pass=store.order('researchpass','m08_080_pass_request_0001');
assert.equal(pass.receipt.charged,false);
assert.equal(store.snapshot().passActive,true);
assert.equal(store.snapshot().missionClaims[day+':codex'],true);
assert.equal(store.snapshot().missionClaims[day+':stage'],true);
assert.equal(store.snapshot().missionClaims[day+':run'],true);
const reload=engine.createStore({storage,clock});
assert.equal(reload.snapshot().owned.crimson,true);
assert.equal(reload.snapshot().passActive,true);
assert.equal(reload.snapshot().crystals,55);
assert.equal(reload.missionStatus().stage.claimed,true);
assert.equal(storage.read('EVOLVE_V575_BATTLE_SAVE'),'SAVE_PRESERVED');
assert.equal(storage.read('EVOLVE_M03_ENTITLEMENT_SAVE'),'ENTITLEMENT_PRESERVED');
const original=storage.read(engine.storageKey);
storage.setItem(engine.storageKey,'{broken');
assert.throws(()=>reload.snapshot(),/STORE_DATA_INVALID/);
assert.equal(storage.read(engine.storageKey),'{broken','do not erase corrupt save');
storage.setItem(engine.storageKey,original);
const j=fs.readFileSync(path.join(__dirname,'../web/m08-mission-rewards-v624.js'),'utf8');
assert.equal(j,fs.readFileSync(path.join(__dirname,'../dist/m08-mission-rewards-v624.js'),'utf8'));
assert.ok(j.includes('m08RewardWalletV624'));
assert.ok(j.includes('aria-live'));
assert.ok(!j.includes('setInterval('));
const index=fs.readFileSync(path.join(__dirname,'../dist/index.html'),'utf8');
assert.ok(index.indexOf('shop-experience-v621.js')<index.indexOf('m08-mission-rewards-v624.js'));
assert.equal((index.match(/m08-mission-rewards-v624\.js/g)||[]).length,1);
assert.equal(engine.mode,'LOCAL_PREVIEW_NO_BILLING');
console.log('M08 80% PASS: stage/run/codex +25, first bonus, permanent crimson purchase, pass and save recovery, no real billing.');
