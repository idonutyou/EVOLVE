'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const api=require('../web/m08-mission-rewards-v624.js');
assert.equal(api.explainError(new Error('ALREADY_CLAIMED')),'이미 받은 보상입니다.');
assert.match(api.explainError(new Error('STORAGE_WRITE_FAILED')),/지급되지 않았습니다/);
assert.match(api.explainError(new Error('MISSION_NOT_COMPLETE')),/오늘/);
assert.match(api.explainError(new Error('MISSION_SOURCE_CORRUPT')),/기록/);
assert.match(api.explainError(new Error('BALANCE_LIMIT')),/상한/);
assert.match(api.explainError(new Error('UNEXPECTED_FAILURE')),/수령하지 못했습니다/);
assert.equal(api.explainError(null),api.explainError(new Error('UNKNOWN')));
const web=fs.readFileSync(path.join(__dirname,'../web/m08-mission-rewards-v624.js'),'utf8');
const dist=fs.readFileSync(path.join(__dirname,'../dist/m08-mission-rewards-v624.js'),'utf8');
assert.equal(web,dist);
assert.ok(web.includes('if(day!==currentDay)'),'KST rollover clears stale message');
assert.ok(web.includes('aria-live'),'accessible feedback');
assert.ok(web.includes('@media(max-width:350px)'),'narrow mobile wraps action buttons');
assert.ok(web.includes('refreshMode:\'EVENT_DRIVEN\''),'preserves event-driven no-poll refresh');
assert.equal(web.includes('setInterval('),false,'no idle polling regression');
console.log('M08 70% PASS: friendly failure feedback, KST day stale message reset, narrow mobile accessibility and event-driven display.');
