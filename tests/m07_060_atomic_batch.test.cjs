'use strict';
const assert=require('node:assert/strict');
const {createTestBatchGate,fenceSnapshot}=require('../monetization/m07/mission-batch-gate-060.cjs');
const {restoreTestJournal}=require('../monetization/m07/mission-journal-050.cjs');
const {paidMonthWindow}=require('../monetization/m07/paid-month-calendar-v1.cjs');
const opts={accountId:'account_test_060',freeCycleId:'free_test_060',freeStartUtc:'2026-10-28T00:00:00.000Z',freeDays:28,paidMonth:'2026-10'};
const events={run:'m07_daily_first_run',stage:'m07_daily_stage_activity',weekly:'m07_weekly_codex_discovery'};
const types={run:'RUN_COMPLETED_VERIFIED',stage:'STAGE_ACTIVITY_VERIFIED',weekly:'CODEX_DISCOVERY_VERIFIED'};
const when=d=>new Date(Date.parse(opts.freeStartUtc)+d*86400000).toISOString();
const ev=(key,id,time,extra={})=>({accountId:opts.accountId,freeCycleId:opts.freeCycleId,missionId:events[key],eventType:types[key],eventId:id,eventUtc:time,...extra});
const batch=(id,rev,items)=>({requestId:id,expectedRevision:rev,events:items});
const g=createTestBatchGate(opts);
assert.equal(g.readRevision(),0);
assert.equal(g.snapshot(when(0)).paidState,'DRAFT_DISABLED');
assert.equal(g.claimReward().realGrants,0);
assert.equal(g.purchasePass().charged,0);
const first=batch('request_001',0,[ev('run','event_run_001',when(0)),ev('stage','event_stage_001',when(0))]);
assert.equal(g.tryBatch(first).ok,true);
assert.equal(g.readRevision(),1);
assert.equal(g.snapshot(when(0)).simulatedAcceptedEvents,2);
assert.equal(g.tryBatch(first).replayed,true);
assert.equal(g.tryBatch(batch('request_001',1,[ev('run','event_diff',when(1))])).reason,'REQUEST_ID_CONFLICT');
assert.equal(g.tryBatch(batch('request_stale',0,[ev('run','event_stale',when(1))])).reason,'STALE_EXPECTED_REVISION');
const saved=g.exportTestJournal();
const rejected=g.tryBatch(batch('request_invalid',1,[ev('run','event_valid',when(1)),ev('stage','event_fake',when(1),{eventType:'BAD_TYPE'})]));
assert.equal(rejected.ok,false);
assert.equal(rejected.failedAt,1);
assert.equal(g.exportTestJournal(),saved);
assert.equal(g.snapshot(when(1)).missions[0].previewCount,0);
assert.equal(g.tryBatch(batch('request_duplicate',1,[ev('run','event_valid',when(1)),ev('run','event_cap',when(0))])).reason,'PERIOD_CAP_REACHED');
assert.equal(g.exportTestJournal(),saved);
assert.equal(g.tryBatch(batch('request_empty',1,[])).reason,'INVALID_BATCH_SIZE');
assert.equal(g.tryBatch(batch('request_large',1,Array(33).fill(ev('run','event_big',when(1))))).reason,'INVALID_BATCH_SIZE');
assert.equal(g.tryBatch(batch('request_wrong',1,[ev('run','event_actor',when(1),{accountId:'account_other'})])).reason,'INVALID_TEST_EVENT');
assert.equal(g.tryBatch(batch('request_date',1,[ev('run','event_bad_date','2026-02-30T00:00:00.000Z')])).reason,'INVALID_TEST_EVENT');
assert.equal(g.tryBatch(batch('request_expired',1,[ev('run','event_expired',when(28))])).reason,'OUTSIDE_FREE_PERIOD');
assert.throws(()=>g.tryBatch({...first,adminEnabled:true}),/BATCH_FIELDS_INVALID/);
assert.equal(g.readRevision(),1);
assert.equal(g.tryBatch(batch('request_002',1,[ev('run','event_run_day2',when(1))])).ok,true);
assert.equal(g.tryBatch(batch('request_003',2,[ev('weekly','event_week1',when(0))])).ok,true);
assert.equal(g.tryBatch(batch('request_004',3,[ev('weekly','event_week2',when(5))])).ok,true);
assert.equal(g.readRevision(),4);
const scope={accountId:opts.accountId,freeCycleId:opts.freeCycleId,currentRevision:4};
assert.equal(fenceSnapshot({...scope,incoming:{...opts,revision:3}}).reason,'STALE_SNAPSHOT');
assert.equal(fenceSnapshot({...scope,incoming:{...opts,revision:5}}).reason,'FUTURE_REVISION_NEEDS_AUTHORITY');
assert.equal(fenceSnapshot({...scope,incoming:{...opts,revision:4}}).apply,true);
assert.equal(fenceSnapshot({...scope,incoming:{...opts,accountId:'account_other',revision:4}}).reason,'SCOPE_MISMATCH');
assert.equal(fenceSnapshot({...scope,incoming:null}).reason,'SNAPSHOT_INVALID');
assert.equal(paidMonthWindow('2026-10').days,31);
assert.equal(paidMonthWindow('2028-02').days,29);
const paidEnd='2026-10-31T15:00:00.000Z';
assert.equal(g.snapshot(paidEnd).paidActive,false);
assert.equal(g.snapshot(paidEnd).freeActive,true);
let rev=4;
for(let d=2;d<28;d++){
 const items=[ev('run','event_run_'+d,when(d)),ev('stage','event_stage_'+d,when(d))];
 const cmd=batch('request_day_'+d,rev,items);
 assert.equal(g.tryBatch(cmd).ok,true,'day '+d);
 rev++;
 assert.equal(g.tryBatch(cmd).replayed,true);
}
assert.equal(g.readRevision(),rev);
assert.equal(g.tryBatch(batch('request_overtime',rev,[ev('run','event_after',when(28))])).reason,'OUTSIDE_FREE_PERIOD');
const restored=restoreTestJournal(g.exportTestJournal());
assert.equal(restored.snapshot(paidEnd).freeActive,true);
assert.equal(restored.snapshot(paidEnd).paidActive,false);
assert.equal(restored.snapshot(when(28)).freeActive,false);
assert.equal(restored.snapshot(when(28)).realRewardsGranted,0);
assert.equal(g.claimReward().realGrants,0);
assert.equal(g.purchasePass().owned,false);
console.log('M07 60% PASS: 28-day atomic batch replay, stale fences, paid monthly, no grants');
