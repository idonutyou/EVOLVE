'use strict';
if(process.env.NODE_ENV!=='development'||process.env.ENABLE_M03_DEV_SERVER!=='1')throw Error('M03_DISABLED');
for(const key of ['M03_DATABASE_URL','M03_OIDC_ISSUER','M03_OIDC_AUDIENCE','M03_OIDC_PUBLIC_KEY_PEM'])if(!process.env[key])throw Error('M03_CONFIG_MISSING_'+key);
const {Pool}=require('pg');
const {makeStore}=require('./db.cjs');
const {makeServer}=require('./api.cjs');
const pool=new Pool({connectionString:process.env.M03_DATABASE_URL,ssl:{rejectUnauthorized:true},max:5});
const identity={issuer:process.env.M03_OIDC_ISSUER,audience:process.env.M03_OIDC_AUDIENCE,publicKey:process.env.M03_OIDC_PUBLIC_KEY_PEM};
const server=makeServer({store:makeStore(pool),identity});
server.listen(8787,'127.0.0.1',()=>console.log('M03 local development API. Payments disabled.'));
process.on('SIGTERM',()=>server.close(()=>pool.end()));
